//! The mitigation report, generated from divergence/cases/*/case.yaml. The battery itself is in tests/battery.rs.

use std::error::Error;
use std::path::Path;

use serde::Deserialize;

// Only the report fields. The battery test reads the rest.
#[derive(Deserialize)]
struct Case {
    construct: String,
    gap: u32,
    cpp: String,
    naive_does: String,
    side: String,
    mitigation: String,
    naive: String,
    #[serde(default)]
    naive_is_wrong: bool,
}

/// The markdown table for docs/mitigations.md. One row per case folder, sorted by case id.
pub fn report(cases_dir: &Path) -> Result<String, Box<dyn Error>> {
    let mut rows = Vec::new();
    for entry in std::fs::read_dir(cases_dir)? {
        let dir = entry?.path();
        if !dir.is_dir() {
            continue;
        }
        let id = dir.file_name().unwrap_or_default().to_string_lossy().into_owned();
        let yaml = dir.join("case.yaml");
        let case: Case = serde_yaml::from_str(&std::fs::read_to_string(&yaml)?).map_err(|e| format!("{}: {e}", yaml.display()))?;
        let verdict = if case.naive_is_wrong { "verifies, wrong".to_string() } else { case.naive };
        // A cell is one line. A pipe would end it early.
        let cell = |s: &str| s.split_whitespace().collect::<Vec<_>>().join(" ").replace('|', "\\|");
        let cells = [id.clone(), cell(&case.construct), case.gap.to_string(), cell(&case.cpp), cell(&case.naive_does), verdict, cell(&case.mitigation), case.side];
        rows.push((id, format!("| {} |", cells.join(" | "))));
    }
    rows.sort();
    let mut out = String::from("# Mitigations\n\nGenerated by `cargo run -p divergence` from `divergence/cases/*/case.yaml`. Do not edit by hand.\n\n");
    out.push_str("| Case | Construct | Gap | C++ does | Naive model does | Naive verdict | Mitigation | Side |\n| --- | --- | --- | --- | --- | --- | --- | --- |\n");
    for (_, row) in rows {
        out.push_str(&row);
        out.push('\n');
    }
    Ok(out)
}
