//! The mitigation report of one prover, generated from divergence/<prover>/cases/*/case.yaml.
//! The battery itself is in tests/battery.rs.

use std::error::Error;
use std::fmt::Display;
use std::path::Path;

use serde::{Deserialize, Serialize};

/// What Dafny says about a file. The values are those of divergence/README.md, and they print as they are written.
#[derive(Deserialize, Serialize, PartialEq)]
#[serde(rename_all = "snake_case")]
enum Verdict {
    Verifies,
    Fails,
    TypeError,
}

/// Where the mitigation lives. The values are those of divergence/README.md.
#[derive(Deserialize, Serialize)]
#[serde(rename_all = "lowercase")]
enum Side {
    Model,
    Contract,
    Cpp,
    Gate,
    None,
}

// Only the report fields. The battery test reads the rest.
#[derive(Deserialize)]
struct Case {
    construct: String,
    standard: String,
    gap: u32,
    cpp: String,
    naive_does: String,
    side: Side,
    mitigation: String,
    naive: Verdict,
    #[serde(default)]
    naive_is_wrong: bool,
}

/// An enum value as it is written in case.yaml.
fn word<T: Serialize>(v: &T) -> Result<String, Box<dyn Error>> {
    Ok(serde_yaml::to_string(v)?.trim().to_string())
}

/// The markdown table for docs/mitigations-<prover>.md. The cases are in `prover_dir/cases`, and the prover
/// is the name of `prover_dir`. One row per case folder, sorted by case id.
pub fn report(prover_dir: &Path) -> Result<String, Box<dyn Error>> {
    let prover = prover_dir.file_name().unwrap_or_default().to_string_lossy().into_owned();
    let cases_dir = prover_dir.join("cases");
    let mut rows = Vec::new();
    for entry in std::fs::read_dir(&cases_dir).map_err(|e| format!("{}: {e}", cases_dir.display()))? {
        let dir = entry?.path();
        if !dir.is_dir() {
            continue;
        }
        let id = dir.file_name().unwrap_or_default().to_string_lossy().into_owned();
        let yaml = dir.join("case.yaml");
        // Every error names the file, so a wrong case.yaml is found at once.
        let at = |e: &dyn Display| format!("{}: {e}", yaml.display());
        let case: Case = serde_yaml::from_str(&std::fs::read_to_string(&yaml).map_err(|e| at(&e))?).map_err(|e| at(&e))?;
        // A naive model that Dafny refuses cannot also be wrong.
        if case.naive_is_wrong && case.naive != Verdict::Verifies {
            return Err(at(&"naive_is_wrong needs naive: verifies").into());
        }
        let verdict = if case.naive_is_wrong { "verifies, wrong".to_string() } else { word(&case.naive)? };
        // A cell is one line. A pipe would end it early.
        let cell = |s: &str| s.split_whitespace().collect::<Vec<_>>().join(" ").replace('|', "\\|");
        let cells = [id.clone(), cell(&case.construct), cell(&case.standard), case.gap.to_string(), cell(&case.cpp), cell(&case.naive_does), verdict, cell(&case.mitigation), word(&case.side)?];
        rows.push((id, format!("| {} |", cells.join(" | "))));
    }
    rows.sort();
    let mut out = format!("# Mitigations: {prover}\n\nGenerated by `cargo run -p divergence -- {prover}` from `divergence/{prover}/cases/*/case.yaml`. Do not edit by hand.\n\nThe fields are explained in divergence/README.md.\n\n");
    out.push_str("| Case | Construct | Standard | Gap | C++ does | Naive model does | Naive verdict | Mitigation | Side |\n| --- | --- | --- | --- | --- | --- | --- | --- | --- |\n");
    for (_, row) in rows {
        out.push_str(&row);
        out.push('\n');
    }
    Ok(out)
}
